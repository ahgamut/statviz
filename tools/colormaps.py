"""Writes web/js/gl/colormaps.js: 256-entry RGB lookup tables from matplotlib.

Usage: venv/bin/python tools/colormaps.py   (needs matplotlib in the venv)
"""
import base64
import pathlib

import matplotlib
import numpy as np

# (name, cyclic, source). Cyclic maps are sampled at i/256 so they wrap.
MAPS = [
    ("viridis", False, "CC0, Smith & van der Walt"),
    ("magma", False, "CC0, Smith & van der Walt"),
    ("inferno", False, "CC0, Smith & van der Walt"),
    ("plasma", False, "CC0, Smith & van der Walt"),
    ("twilight", True, "MIT, Bastian Bechtold"),
]

out = pathlib.Path(__file__).resolve().parent.parent / "web/js/gl/colormaps.js"
lines = [
    f"// Generated by tools/colormaps.py from matplotlib {matplotlib.__version__}; do not edit.",
    "// rgb: base64 of 256 RGB8 entries.",
    "export const COLORMAPS = [",
]
for name, cyclic, source in MAPS:
    x = np.arange(256) / 256 if cyclic else np.linspace(0, 1, 256)
    rgb = np.round(matplotlib.colormaps[name](x)[:, :3] * 255).astype(np.uint8)
    data = base64.b64encode(rgb.tobytes()).decode()
    lines.append(f"  {{ name: '{name}', cyclic: {str(cyclic).lower()},  // {source}")
    lines.append(f"    rgb: '{data}' }},")
lines.append("];")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out}")
